        /// <summary>
        /// The country or area X.121 Annex J gives a Data Country Code.
        /// </summary>
        /// <param name="dcc">
        /// Three digits; a longer number (a DNIC or a whole address) is looked up by its first three.
        /// </param>
        /// <param name="name">
        /// The name, or empty when Annex J lists none for the code.
        /// </param>
        /// <returns>
        /// True when Annex J names the code.
        /// </returns>
        public static bool TryGetCountry(string? dcc, out string name)
        {
            name = string.Empty;
            if (dcc == null || dcc.Length < 3)
            {
                return false;
            }

            if (Names.TryGetValue(dcc.Length == 3 ? dcc : dcc.Substring(0, 3), out string? found))
            {
                name = found;
                return true;
            }

            return false;
        }
