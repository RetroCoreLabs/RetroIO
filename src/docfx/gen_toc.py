#!/usr/bin/env python3
"""Writes src/docfx/packages/toc.yml: the guide pages of the documentation site.

One command regenerates the list, from the files git tracks (an untracked note must never reach the
site's navigation, or the clean checkout that CI builds has a link to a file it does not have):

    python src/docfx/gen_toc.py            write src/docfx/packages/toc.yml
    python src/docfx/gen_toc.py --check    exit 1 when the file on disk is not what this script writes (CI runs this)

What is a guide, and what stays off the site (the policy):

  ON   README.md of every package folder src/<Package>/ that has a src/*.csproj
  ON   the long guides that sit next to a package's code: GUIDES below
  ON   the README.md of every tool under src/tools/ (package READMEs link to them)
  ON   CHANGELOG.md
  OFF  BUGS.md (a bug list, it changes with every fix), *-TODO.md (plans), TOOL-SUMMARY.md,
       tests/ (not shipped), DOC/ and X25Emulator/ (test data copies),
       the repository front page README.md (the site's home page is index.md)

The API reference is not listed here: DocFX writes it from the XML comments of the projects.
"""
import os
import subprocess
import sys

REPO = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
SRC = "src"
OUT = os.path.join(REPO, SRC, "docfx", "packages", "toc.yml")

# Guides that live inside a package's own src folder: path under src/, then the title shown in the menu.
GUIDES = [
    ("RetroIO.Protocols.Econet/src/README.md", "Econet file server guide"),
    ("RetroIO.Protocols.Xmsg.Api/src/README.md", "XMSG kernel API guide"),
    ("RetroIO.Management.Api/src/README.md", "Management API guide"),
]


def tracked():
    out = subprocess.check_output(["git", "-C", REPO, "ls-files", SRC], text=True)
    return set(out.splitlines())


def build():
    files = tracked()
    packages = []
    for path in sorted(files):
        parts = path.split("/")
        # src/<Package>/README.md where the package has a project under src/<Package>/src/*.csproj
        if len(parts) == 3 and parts[2] == "README.md" and parts[1].startswith("RetroIO."):
            package = parts[1]
            has_project = any(
                f.startswith(SRC + "/" + package + "/src/") and f.endswith(".csproj") for f in files
            )
            if has_project:
                packages.append(package)

    lines = [
        "# Generated by src/docfx/gen_toc.py from the files git tracks. Edit the script or the README files, then run it again.",
        "- name: Packages",
        "  items:",
    ]
    for package in packages:
        lines.append("  - name: " + package)
        lines.append("    href: ../../" + package + "/README.md")

    present = [(g, t) for g, t in GUIDES if SRC + "/" + g in files]
    if present:
        lines.append("- name: Guides")
        lines.append("  items:")
        for guide, title in present:
            lines.append("  - name: " + title)
            lines.append("    href: ../../" + guide)

    tools = sorted(
        f for f in files
        if f.startswith(SRC + "/tools/") and f.endswith("/README.md") and f.count("/") == 3
    )
    if tools:
        lines.append("- name: Tools")
        lines.append("  items:")
        for tool in tools:
            name = tool.split("/")[2]
            lines.append("  - name: " + name)
            lines.append("    href: ../../" + tool[len(SRC) + 1:])

    if SRC + "/CHANGELOG.md" in files:
        lines.append("- name: Changelog")
        lines.append("  href: ../../CHANGELOG.md")

    return "\n".join(lines) + "\n"


def main():
    wanted = build()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current.replace("\r\n", "\n") != wanted:
            print("src/docfx/packages/toc.yml is out of date: run  python src/docfx/gen_toc.py  and commit the result.")
            return 1
        print("src/docfx/packages/toc.yml is current.")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(wanted)
    print("wrote", os.path.relpath(OUT, REPO), "-", wanted.count("\n"), "lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
