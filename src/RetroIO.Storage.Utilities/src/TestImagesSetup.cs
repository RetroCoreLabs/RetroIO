using System.IO;

namespace RetroIO.Storage.Utilities
{
    /// <summary>
    /// Helper class for setting up test images directory structure.
    /// Creates the standard RetroFS test images folder in the user's data directory.
    /// </summary>
    public static class TestImagesSetup
    {
        /// <summary>
        /// Creates the complete test images directory structure.
        /// Creates subdirectories for each supported filesystem type.
        /// </summary>
        public static void CreateDirectoryStructure()
        {
            string testImagesRoot = PathHelper.EnsureDirectory(PathHelper.GetTestImagesPath());

            // Create subdirectories for each filesystem type
            string[] filesystems = new[]
            {
                "d64",      // Commodore 1541
                "ndfs",     // Norsk Data
                "hfs",      // Macintosh HFS/HFS+
                "adf",      // Amiga
                "prodos",   // Apple II ProDOS
                "dfs"       // BBC Micro DFS/ADFS
            };

            for (int i = 0; i < filesystems.Length; i++)
            {
                PathHelper.EnsureDirectory(Path.Combine(testImagesRoot, filesystems[i]));
            }

            // Create README in test images root
            CreateReadmeFile(testImagesRoot);
        }

        private static void CreateReadmeFile(string testImagesPath)
        {
            string readmePath = Path.Combine(testImagesPath, "README.md");

            if (File.Exists(readmePath))
            {
                return; // Don't overwrite existing README
            }

            string readmeContent = @"# RetroFS Test Images

This directory contains disk images for testing RetroFS filesystem drivers.

## Directory Structure

```
test-images/
├── d64/          Commodore 1541 disk images (.d64)
├── ndfs/         Norsk Data filesystem images
├── hfs/          Macintosh HFS/HFS+ images (.hfs, .dmg)
├── adf/          Amiga ADF disk images (.adf)
├── prodos/       Apple II ProDOS images (.po, .dsk)
└── dfs/          BBC Micro DFS/ADFS images (.ssd, .dsd, .adf)
```

## Adding Test Images

Place your disk images in the appropriate subdirectory:

- **D64 files** → `d64/`
- **HFS files** → `hfs/`
- **ADF files** → `adf/`
- etc.

## Usage

The demo application and unit tests will automatically find images in this location:

```bash
# Demo will search this directory
dotnet run --project RetroFS.Demo

# Or specify a path directly
dotnet run --project RetroFS.Demo d64/my-disk.d64
```

## Location

- **Windows**: `%USERPROFILE%\Documents\RetroFS\test-images`
- **Linux/macOS**: `~/.local/share/retrofs/test-images`

## Creating Test Images

See the main RetroFS documentation for instructions on creating test disk images for each filesystem type.

---

Generated by RetroFS.Utilities - https://github.com/yourusername/RetroFS
";

            File.WriteAllText(readmePath, readmeContent);
        }
    }
}
