using NUnit.Framework;
using RetroIO.Protocols.X25.Protocols;

namespace RetroIO.Protocols.X25.Tests
{
    /// <summary>
    /// Padding in the data stream from the host to the terminal, X.3 (03/00) 3.9 and 3.14.
    /// </summary>
    /// <remarks>
    /// The padding character is NUL (X.28 3.5.20: "The padding character will be 0/0 (NUL)"). Added 2026-11-21 for
    /// RetroIO BUGS.md item 44; before that no padding was sent at all.
    /// </remarks>
    [TestFixture]
    public class X3PaddingTests
    {
        /// <summary>
        /// X.3 3.9: "the number of padding characters to be generated by the PAD after a carriage return character is
        /// transmitted to the start-stop mode DTE".
        /// </summary>
        [Test]
        public void Parameter9_PutsThatManyNulsAfterEachCarriageReturn()
        {
            X3 x3 = new X3();
            x3.SetParameter(X3.ParameterNumber.PADDING_AFTER_CR, 3);

            Assert.That(x3.ProcessIncomingText("A\rB\r"), Is.EqualTo("A\r\0\0\0B\r\0\0\0"));
        }

        /// <summary>
        /// X.3 3.14: "the number of padding characters to be generated by the PAD after a linefeed character is
        /// transmitted to the start-stop mode DTE during the data transfer state".
        /// </summary>
        [Test]
        public void Parameter14_PutsThatManyNulsAfterEachLinefeed()
        {
            X3 x3 = new X3();
            x3.SetParameter(X3.ParameterNumber.PADDING_AFTER_LINE_FEED, 2);

            Assert.That(x3.ProcessIncomingText("A\nB"), Is.EqualTo("A\n\0\0B"));
        }

        /// <summary>
        /// A linefeed inserted by parameter 13 value 1 is also a linefeed transmitted to the terminal, so parameter 14
        /// pads it. The CR's own padding follows the CR (X.3 3.9 "after a carriage return").
        /// </summary>
        [Test]
        public void AnInsertedLinefeed_IsPaddedToo()
        {
            X3 x3 = new X3();
            x3.SetParameter(X3.ParameterNumber.LINE_FEED_INSERTION, 1);
            x3.SetParameter(X3.ParameterNumber.PADDING_AFTER_CR, 1);
            x3.SetParameter(X3.ParameterNumber.PADDING_AFTER_LINE_FEED, 2);

            Assert.That(x3.ProcessIncomingText("A\r"), Is.EqualTo("A\r\0\n\0\0"));
        }

        /// <summary>
        /// With both parameters 0 the text is unchanged.
        /// </summary>
        [Test]
        public void NoPadding_LeavesTheTextAlone()
        {
            X3 x3 = new X3();
            x3.SetParameter(X3.ParameterNumber.PADDING_AFTER_CR, 0);
            x3.SetParameter(X3.ParameterNumber.PADDING_AFTER_LINE_FEED, 0);

            Assert.That(x3.ProcessIncomingText("A\r\nB"), Is.EqualTo("A\r\nB"));
        }
    }
}
