# -*- coding: utf-8 -*-
# Generator for the XMSG enum .cs files.
# Reads the AUTHORITATIVE xmsg-constants.json and emits one C# file per enum,
# with a 3-line /// <summary> per member taken verbatim from the official desc.
import json, os, io

# Paths are resolved relative to this script so the tool is portable (no absolute
# paths). Layout:  XMSG/xmsg-constants.json  and  XMSG/SRC/tools/gen-xmsg-enums.py
# -> the enum output lands in  XMSG/SRC/Xmsg.Protocol/Enums.
_HERE = os.path.dirname(os.path.abspath(__file__))          # XMSG/SRC/tools
XMSG  = os.path.abspath(os.path.join(_HERE, "..", ".."))    # XMSG (holds the JSON)
OUT   = os.path.join(_HERE, "..", "RetroIO.Protocols.Xmsg", "src", "Enums") # XMSG/SRC/Xmsg.Protocol/Enums
os.makedirs(OUT, exist_ok=True)

with io.open(os.path.join(_HERE, "..", "RetroIO.Protocols.Xmsg", "docs", "xmsg-constants.json"), "r", encoding="utf-8") as f:
    J = json.load(f)

def esc(s):
    # XML-escape for /// doc comments.
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

def wrap_summary(desc, indent="    "):
    out = []
    out.append(indent + "/// <summary>")
    out.append(indent + "/// " + esc(desc))
    out.append(indent + "/// </summary>")
    return "\n".join(out)

def header():
    return ("// <auto-generated>\n"
            "// Generated from SINTRAN/XMSG/xmsg-constants.json (XMSG version M, 1988-08-18).\n"
            "// Source include file: SINTRAN/XMSG/XMSG-PL-VALUES-M.INCL\n"
            "// Descriptions are copied verbatim from the official ND include-file comments.\n"
            "// Do not edit by hand - regenerate from the JSON.\n"
            "// </auto-generated>\n\n"
            "namespace NDInsight.Sintran.Xmsg\n{\n")

def emit_plain(name, section, typedecl, type_summary, seen_alias_ok=True, value_transform=None):
    entries = J[section]
    lines = [header()]
    lines.append(wrap_summary(type_summary))
    lines.append("    public enum " + typedecl)
    lines.append("    {")
    seen = {}
    body = []
    for sym, obj in entries.items():
        v = obj["value"]
        if value_transform:
            vexpr = value_transform(v)
        else:
            vexpr = str(v)
        body.append(wrap_summary(obj["desc"], "        "))
        body.append("        " + sym + " = " + vexpr + ",")
        body.append("")
    if body and body[-1] == "":
        body.pop()
    lines.append("\n".join(body))
    lines.append("    }")
    lines.append("}")
    with io.open(os.path.join(OUT, name + ".cs"), "w", encoding="utf-8", newline="\r\n") as fo:
        fo.write("\n".join(lines) + "\n")

# ---- XmsgFunction (XF*) ----
