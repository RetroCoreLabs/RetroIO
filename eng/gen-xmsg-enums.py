# ---- XmsgOption ([Flags], values are BIT NUMBERS -> mask = 1 << bit) ----
def emit_options():
    entries = J["option_bits"]
    lines = [header()]
    lines.append("    /// <summary>")
    lines.append("    /// MON 200B T-register option bits, OR-ed into the high-order byte alongside")
    lines.append("    /// the function code. Each flag mask is <c>1 &lt;&lt; bit</c>.")
    lines.append("    /// </summary>")
    lines.append("    [System.Flags]")
    lines.append("    public enum XmsgOption : ushort")
    lines.append("    {")
    lines.append("        /// <summary>")
    lines.append("        /// No option bits set.")
    lines.append("        /// </summary>")
    lines.append("        None = 0,")
    lines.append("")
    body = []
    for sym, obj in entries.items():
        bit = obj["value"]
        mask = 1 << bit
        body.append("        /// <summary>")
        body.append("        /// " + esc(obj["desc"]))
        body.append("        /// </summary>")
        body.append("        /// <remarks>")
        body.append("        /// Bit " + str(bit) + " (mask 0x" + format(mask, "04X") + ") in the MON 200B T-register high byte.")
        body.append("        /// </remarks>")
        body.append("        " + sym + " = 1 << " + str(bit) + ",")
        body.append("")
    if body and body[-1] == "":
        body.pop()
    lines.append("\n".join(body))
    lines.append("    }")
    lines.append("}")
    with io.open(os.path.join(OUT, "XmsgOption.cs"), "w", encoding="utf-8", newline="\r\n") as fo:
        fo.write("\n".join(lines) + "\n")
emit_options()

# ---- XROUT sub-service enums (split by parent service to avoid value collisions) ----
# Groupings taken from XMSG-API.md section 6.4.
SUBGROUPS = {
    "XroutSetCrashInfoSubservice": (
        "Sub-service codes (parameter 1) for the XSSCI set-crash-information service.",
        ["XSDAR", "XSDRF", "XSDDF", "XSGDF", "XSDUX", "XSGRF", "XSGAR"]),
    "XroutGetAttributeSubservice": (
        "Sub-service codes (parameter 1) for the XSGAT get/check-attribute service.",
        ["XSGXV", "XSCMG", "XSGCN", "XSGFR", "XSGLO"]),
    "XroutDefineAttributeSubservice": (
        "Sub-service codes (parameter 1) for the XSDAT define/remove-attribute service.",
        ["XSDFR", "XSRFR", "XSECS", "XSDCS", "XSDAL"]),
}
def emit_subgroups():
    src = J["xrout_subservices"]
    for typename, (summary, syms) in SUBGROUPS.items():
        lines = [header()]
        lines.append(wrap_summary(summary))
        lines.append("    public enum " + typename + " : int")
        lines.append("    {")
        body = []
        for sym in syms:
            obj = src[sym]
            body.append(wrap_summary(obj["desc"], "        "))
            body.append("        " + sym + " = " + str(obj["value"]) + ",")
            body.append("")
        if body and body[-1] == "":
            body.pop()
        lines.append("\n".join(body))
        lines.append("    }")
        lines.append("}")
        with io.open(os.path.join(OUT, typename + ".cs"), "w", encoding="utf-8", newline="\r\n") as fo:
            fo.write("\n".join(lines) + "\n")
emit_subgroups()

print("Generated enum files in", OUT)
